def _sentence(text: str, start: int, end: int) -> str:
    left = max((text.rfind(c, 0, start) for c in ".!?\n"), default=-1) + 1
    rights = [r for r in (text.find(c, end) for c in ".!?\n") if r != -1]
    right = min(rights) + 1 if rights else len(text)
    return text[left:right]


def scan_hate(text: str) -> list[Violation]:
    out: list[Violation] = []
    for m in _SEEDS.finditer(text):
        if _CARVEOUT is not None and _CARVEOUT.search(_sentence(text, m.start(), m.end())):
            continue  # 의학/뉴스/교육/인용 문맥 → 위반 아님
        out.append(Violation(
            code="hate",
            category=Category.HATE,
            severity=Severity.HIGH,
            reason="moderation: hate (deterministic Tier-1)",
            start=m.start(), end=m.end(), matched=m.group(0)[:60],
        ))
    return out
